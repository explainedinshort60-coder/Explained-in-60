"""Weekly ad-revenue scorecard (MILESTONES.md).
  python3 engine/scorecard.py add week_start=2026-11-09 shorts_views_wk=... subs_total=... (any columns of metrics/weekly.csv)
  python3 engine/scorecard.py            -> metrics/scorecard.md (actual vs target, status, projected dates)
Status per metric: GREEN >= 100% of target, AMBER 70 to 99%, RED < 70%. Two RED weeks in a row on the same
metric trigger the correction rules in MILESTONES.md."""
import csv, os, sys, datetime as dt
R = os.path.abspath(os.path.join(os.path.dirname(__file__), '..')); M = os.path.join(R, 'metrics')
T = list(csv.DictReader(open(os.path.join(M, 'targets.csv'))))
W = list(csv.DictReader(open(os.path.join(M, 'weekly.csv'))))
KEYS = ['shorts_views_wk', 'longform_views_wk', 'subs_total', 'watch_hours_365', 'revenue_usd_wk']
def f(x):
    try: return float(str(x).replace(',', ''))
    except ValueError: return None
def target_for(week):
    d = dt.date.fromisoformat(week); best = None
    for t in T:
        if dt.date.fromisoformat(t['week_start']) <= d: best = t
    return best or T[0]
def add(kv):
    cols = open(os.path.join(M, 'weekly.csv')).readline().strip().split(',')
    row = {c: '' for c in cols}; row.update(kv)
    rows = [r for r in W if r['week_start'] != row['week_start']] + [row]
    rows.sort(key=lambda r: r['week_start'])
    w = csv.DictWriter(open(os.path.join(M, 'weekly.csv'), 'w', newline=''), fieldnames=cols); w.writeheader(); w.writerows(rows)
def eta(key, goal):
    pts = [(dt.date.fromisoformat(r['week_start']), f(r[key])) for r in W if f(r.get(key)) is not None]
    if len(pts) < 2: return 'need 2+ weeks'
    (d0, v0), (d1, v1) = pts[-2], pts[-1]
    rate = (v1 - v0) / max(1, (d1 - d0).days)
    if v1 >= goal: return 'reached'
    if rate <= 0: return 'not growing'
    return str(d1 + dt.timedelta(days=int((goal - v1) / rate)))
def report():
    L = [f'# Ad-revenue scorecard ({dt.date.today()})', '', 'Generated by `engine/scorecard.py` from metrics/weekly.csv vs metrics/targets.csv. Rules: MILESTONES.md.', '',
         '| Week | ' + ' | '.join(KEYS) + ' |', '|---|' + '---|' * len(KEYS)]
    streak = {}
    for r in W:
        t = target_for(r['week_start']); cells = []
        for k in KEYS:
            a, g = f(r.get(k)), f(t.get(k))
            if a is None: cells.append('n/a'); continue
            if not g: cells.append(f'{a:,.0f}'); continue
            p = a / g; s = 'GREEN' if p >= 1 else 'AMBER' if p >= 0.7 else 'RED'
            streak[k] = streak.get(k, 0) + 1 if s == 'RED' else 0
            cells.append(f'{a:,.0f} / {g:,.0f} {s}')
        L.append(f"| {r['week_start']} | " + ' | '.join(cells) + ' |')
    L += ['', '## Projected dates (linear, last 2 weeks)', '',
          f"- 1,000 subscribers: {eta('subs_total', 1000)} (needed before Feb 1, 2027)",
          f"- 4,000 watch hours (365 days): {eta('watch_hours_365', 4000)} (old rule, apply before Feb 1, 2027)",
          f"- 8,000 watch hours (365 days): {eta('watch_hours_365', 8000)} (new rule after Feb 1, 2027)", '']
    alarms = [k for k, n in streak.items() if n >= 2]
    L.append('## Alarms' if alarms else '## Alarms: none')
    for k in alarms: L.append(f'- {k}: RED two weeks in a row. Apply the correction rule for it in MILESTONES.md.')
    open(os.path.join(M, 'scorecard.md'), 'w').write('\n'.join(L) + '\n'); print('\n'.join(L))
if __name__ == '__main__':
    if len(sys.argv) > 1 and sys.argv[1] == 'add': add(dict(a.split('=', 1) for a in sys.argv[2:])); W = list(csv.DictReader(open(os.path.join(M, 'weekly.csv'))))
    report()
